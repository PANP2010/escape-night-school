// Prefer br, then gzip on equal q values. An absent/empty header always preserves original bytes.
function encodingQuality(header: string | undefined): (encoding: string) => number {
  const quality = new Map<string, number>();
  for (const item of (header ?? '').split(',')) {
    const [name, ...params] = item.toLowerCase().split(';').map(part => part.trim());
    if (!name) continue;
    const q = params.find(p => p.trim().startsWith('q='))?.trim().slice(2) ?? '1';
    const value = /^(?:0(?:\.\d{0,3})?|1(?:\.0{0,3})?)$/.test(q) ? Number(q) : 0;
    quality.set(name, Math.max(quality.get(name) ?? 0, value));
  }
  return encoding => quality.get(encoding) ?? (encoding === 'identity'
    ? (quality.get('*') === 0 ? 0 : 1)
    : header?.trim() ? quality.get('*') ?? 0 : 0);
}

async function serveStatic(req: IncomingMessage, res: ServerResponse, pathname: string): Promise<void> {
  // Path traversal guard: resolved file must stay inside DIST, including the path separator.
  let file = normalize(join(DIST, decodeURIComponent(pathname)));
  if (file !== DIST && !file.startsWith(`${DIST}${sep}`)) { res.writeHead(403).end(); return; }
  let info = await stat(file).catch(() => undefined);
  if (!info?.isFile()) { file = join(DIST, 'index.html'); info = await stat(file).catch(() => undefined); }
  if (!info?.isFile()) { res.writeHead(404).end('client not built'); return; }
  const quality = encodingQuality(req.headers['accept-encoding']);
  let selected = { file, size: info.size, encoding: 'identity', q: quality('identity') };
  // Sidecars are generated by build:client, never compressed or retained in memory by this process.
  for (const encoding of ['gzip', 'br']) {
    const q = quality(encoding);
    if (q <= 0 || q < selected.q) continue;
    const compressed = `${file}.${encoding === 'gzip' ? 'gz' : 'br'}`;
    const sidecar = await stat(compressed).catch(() => undefined);
    if (sidecar?.isFile() && sidecar.mtimeMs >= info.mtimeMs && sidecar.size < info.size) {
      selected = { file: compressed, size: sidecar.size, encoding, q };
    }
  }
  if (selected.q <= 0) {
    res.writeHead(406, { vary: 'Accept-Encoding', 'cache-control': 'no-store' }).end(); return;
  }
  res.writeHead(200, {
    'content-type': MIME[extname(file)] ?? 'application/octet-stream',
    'content-length': selected.size,
    vary: 'Accept-Encoding',
    ...(selected.encoding === 'identity' ? {} : { 'content-encoding': selected.encoding }),
    'cache-control': file === join(DIST, 'version.json') ? 'no-store'
      : file.includes(`${DIST}/assets/`) ? 'public, max-age=31536000, immutable' : 'no-cache',
  });
  if (req.method === 'HEAD') { res.end(); return; }
  const stream = createReadStream(selected.file);
  // A removed/unreadable asset must not produce an unhandled stream error or terminate the server.
  stream.on('error', () => {
    if (res.headersSent) res.destroy();
    else {
      res.removeHeader('content-encoding');
      res.removeHeader('content-length');
      res.writeHead(500, { 'cache-control': 'no-store' }).end();
    }
  });
  res.on('close', () => stream.destroy());
  res.on('error', () => stream.destroy());
  stream.pipe(res);
}

const http = createServer((req, res) => {
  const url = new URL(req.url ?? '/', 'http://x');
  if (handleDownloads(req, res, url, resolve(process.env.DOWNLOADS_DIR ?? '../downloads'))) return;
  if (handleFeedback(req, res, url, feedbackOptions)) return;
  if (url.pathname === '/api/leaderboard') {
    const difficulty = url.searchParams.get('difficulty') ?? 'story', team = url.searchParams.get('team') ?? 'solo';
    if (req.method !== 'GET' && req.method !== 'HEAD') { res.writeHead(405, { allow: 'GET, HEAD' }).end(); return; }
    if (!isDifficultyId(difficulty) || (team !== 'solo' && team !== 'team')) { res.writeHead(400).end(); return; }
    void leaderboardReady.then(() => {
      res.writeHead(200, { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store', 'access-control-allow-origin': '*' });
      res.end(req.method === 'HEAD' ? undefined : JSON.stringify({ difficulty, team, entries: leaderboard.list(difficulty, team) }));
    });
    return;
  }
  if (url.pathname === '/healthz') {
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ ok: true, rooms: rooms.rooms.size }));
    return;
  }
  void serveStatic(req, res, url.pathname).catch((error: unknown) => {
    if (res.headersSent) res.destroy();
    else res.writeHead(error instanceof URIError ? 400 : 500).end();
  });
});

const wss = new WebSocketServer({ server: http, path: '/ws', maxPayload: 16 * 1024 });
let nextId = 1;
const sessions = new ResumeSessions();
const ips = new IpConnections();
const live = new Map<WebSocket, { conn: Conn; lastPong: number; finish: (revoke?: boolean) => void }>();

wss.on('connection', (ws: WebSocket, req: IncomingMessage) => {
  const address = req.socket.remoteAddress ?? 'unknown';
  if (!ips.acquire(address)) { ws.on('error', () => {}); ws.terminate(); return; }
  const conn: Conn = {
    id: nextId++,
    name: '无名',
    send: (m: ServerMsg) => { if (ws.readyState === ws.OPEN) ws.send(encode(m)); },
    sendRaw: (s: string) => { if (ws.readyState === ws.OPEN) ws.send(s); },
  };
  const guard = new MessageGuard();
  let closed = false;
  const finish = (revoke = false) => {
    if (closed) return;
    closed = true;
    live.delete(ws);
    ips.release(address);
    if (revoke) sessions.revoke(conn, Date.now());
    else sessions.disconnect(conn, Date.now());
  };
  const kick = () => { finish(true); ws.terminate(); };
  live.set(ws, { conn, lastPong: Date.now(), finish });
  conn.send({ t: 'welcome', id: conn.id });
  ws.on('pong', () => { const state = live.get(ws); if (state) state.lastPong = Date.now(); });
  ws.on('message', (data, binary) => {
    if (closed) return;
    const now = Date.now();
    if (!guard.allow(now)) { if (guard.kicked) kick(); return; }
    const m = binary ? null : parseClientMsg(data.toString());
    if (!m || (m.t === 'debug' && !conn.room?.canDebug(conn))) {
      guard.invalid();
      if (guard.kicked) kick();
      return;
    }
    if (lobby.handle(conn, m, now, debugEnabled() && process.argv.includes('--l7-preview') ? L7_INDEX : debugEnabled() && process.env.ESCAPE_TEST_LEVEL === '6' ? L6_INDEX : debugEnabled() && process.argv.includes('--l5-preview') ? L5_INDEX : debugEnabled() && process.argv.includes('--l4-preview') ? L4_INDEX : 0)) return;
    switch (m.t) {
      case 'hello': {
        const result = sessions.hello(conn, m.resume, now);
        if ('resumePending' in result) { conn.send({ t: 'welcome', id: conn.id, resumePending: true }); break; }
        if (!result.resumed) conn.name = m.name;
        const { token } = result;
        conn.send({ t: 'welcome', id: conn.id, token, ...(result.resumed ? { resumed: true } : result.resumeFailed ? { resumeFailed: true } : {}) });
        if (result.resumed) result.previous.room?.resume(result.previous, conn, now);
        break;
      }
      case 'heartbeat': break;
      default: conn.room?.handle(conn, m, now);
    }
  });
  ws.on('close', () => finish());
  ws.on('error', (error: Error & { code?: string }) => {
    finish(error.code?.startsWith('WS_ERR_') ?? false);
    ws.terminate();
  });
});

setInterval(() => {
  const now = Date.now();
  sessions.expire(now);
  for (const [ws, state] of live) if (now - state.lastPong >= HEARTBEAT_TIMEOUT_MS) { state.finish(); ws.terminate(); }
  rooms.step(now);
}, TICK_MS);
setInterval(() => {
  for (const [ws, state] of live) {
    if (ws.readyState === ws.OPEN) { ws.ping(); state.conn.send({ t: 'heartbeat' }); }
  }
}, HEARTBEAT_MS);

http.listen(PORT, HOST, () => console.log(`escape server on http://${HOST}:${PORT}`));
